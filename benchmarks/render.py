"""Write benchmarks/results.md from benchmarks/results.json.

The documentation's benchmarks page includes the generated file, so the
published numbers are always the ones the scripts measured. Run it after
``run.py``::

    python benchmarks/render.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOLS = ["dpm-xbrl", "eba-xbridge", "Arelle"]
ORDER = [
    "import",
    "xml-corep",
    "xml-finrep",
    "csv-corep",
    "csv-corep-metadata",
    "csv-finrep",
    "filing-xml-corep",
    "filing-csv-corep",
    "csv-7m-frames",
    "csv-7m-facts",
    "csv-7m-finrep-frames",
    "csv-22m-frames",
    "convert-xml-csv",
    "convert-xml-csv-finrep",
]
# Why a tool has no number for a task. Update these when a tool gains the
# feature.
NOT_APPLICABLE = {
    ("csv-corep", "eba-xbridge"): "cannot read xBRL-CSV",
    ("csv-corep-metadata", "eba-xbridge"): "cannot read xBRL-CSV",
    ("csv-finrep", "eba-xbridge"): "cannot read xBRL-CSV",
    ("filing-xml-corep", "dpm-xbrl"): None,
    ("filing-xml-corep", "Arelle"): "not measured",
    ("filing-csv-corep", "Arelle"): "not measured",
    ("csv-7m-frames", "Arelle"): "not attempted",
    ("csv-7m-facts", "eba-xbridge"): "see the row above",
    ("csv-7m-facts", "Arelle"): "not attempted",
    ("csv-7m-finrep-frames", "eba-xbridge"): "not measured",
    ("csv-7m-finrep-frames", "Arelle"): "not attempted",
    ("csv-22m-frames", "eba-xbridge"): "not measured",
    ("csv-22m-frames", "Arelle"): "not attempted",
    ("convert-xml-csv", "Arelle"): "n/a",
    ("convert-xml-csv-finrep", "Arelle"): "n/a",
    ("csv-corep-metadata", "Arelle"): "n/a",
    ("csv-finrep", "Arelle"): "not measured",
}
NOTES = {
    "import": "Times include starting Python. Arelle runs load the EBA 4.2 "
    "taxonomy packages as part of reading, and count "
    "the filing indicators as facts.",
    "filing-xml-corep": "dpm-xbrl checks the filing rules while it reads, so "
    "its filing-rule rows are read times; eba-xbridge runs "
    "`validate(eba=True)`.",
    "csv-7m-frames": "eba-xbridge cannot read xBRL-CSV; its time on the "
    "7.3-million-fact package is its `validate(eba=True)`.",
    "convert-xml-csv": "dpm-xbrl converts with the EBA 4.2 taxonomy packages "
    "(`write_xbrl_csv(..., taxonomy_packages=...)`), including opening them; "
    "eba-xbridge uses the module metadata it bundles.",
}


def cell(record: dict[str, object] | None, task: str, tool: str) -> str:
    """Format one measurement, or say why there is none.

    Returns:
        str: ``1.23 s, 82 MB``, or a short reason.
    """
    if record is None:
        reason = NOT_APPLICABLE.get((task, tool))
        return reason or "not measured"
    if record["status"]:
        return f"failed: {record['output']}"
    runs = record["runs_s"]
    once = " (1 run)" if len(runs) == 1 else ""
    return f"{record['best_s']:.2f} s, {record['rss_mb']:,} MB{once}"


def main() -> None:
    """Render the results tables."""
    data = json.loads((HERE / "results.json").read_text())
    results = data.get("results", {})
    environment = data.get("environment", {})
    lines = [
        "<!-- Generated by benchmarks/render.py from benchmarks/results.json. -->",
        "",
        f"Measured on {environment.get('date', '?')}: {environment.get('cpu', '?')}, "
        f"{environment.get('cores', '?')} cores, {environment.get('memory', '?')}, "
        f"{environment.get('platform', '?')}; load average when measured "
        f"{', '.join(str(value) for value in environment.get('load_average', []))}. "
        f"dpm-xbrl at commit `{environment.get('dpm_xbrl_commit', '?')}`.",
        "",
        "| Tool | Version | Python |",
        "| --- | --- | --- |",
    ]
    for tool, version in sorted(environment.get("versions", {}).items()):
        lines.append(f"| {tool} | {version['version']} | {version['python']} |")
    lines += [
        "",
        "| Task | " + " | ".join(TOOLS) + " |",
        "| --- |" + " --- |" * len(TOOLS),
    ]
    for task in ORDER:
        records = results.get(task)
        if not records:
            continue
        title = next(iter(records.values()))["title"]
        cells = [cell(records.get(tool), task, tool) for tool in TOOLS]
        lines.append(f"| {title} | " + " | ".join(cells) + " |")
    notes = [NOTES[task] for task in ORDER if task in results and task in NOTES]
    if notes:
        lines += ["", *[f"- {note}" for note in notes]]
    coverage = data.get("coverage")
    if coverage:
        lines += [
            "",
            f"Sample reports read ({coverage['files']} files: the EBA samples and "
            "three synthetic packages):",
            "",
        ]
        lines += [f"- {tool}: {coverage[tool]}" for tool in TOOLS if tool in coverage]
    (HERE / "results.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
